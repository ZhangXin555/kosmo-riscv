`timescale 1ns / 1ps
//==========================================================================
//  counter.sv — 毫秒计时器（"这套程序跑了多少毫秒"的裁判）
//--------------------------------------------------------------------------
//  用途：
//    比赛要求程序跑完后报一个"跑了多少毫秒"。CPU 自己不会数时间，
//    所以外面放一个独立计时器：CPU 在程序开头写一个魔数把它清零并启动，
//    在程序结尾再写一个魔数把它停住，之后读它就知道总耗时。
//
//  编程接口（CPU 通过 store/load 访问 0x8020_0050）：
//    写 0x8000_0000  → 启动（同时把毫秒数清零）
//    写 0xFFFF_FFFF  → 停表（毫秒数不再增加，定格）
//    读 0x8020_0050  → 返回当前毫秒数 cnt_ms
//
//  计时原理：
//    50 MHz 时钟 → 50000 个时钟周期 = 1 ms
//    所以 cnt_1ms 从 0 数到 49999 就产生一个"毫秒脉冲"，
//    每来一次脉冲 cnt_ms 加 1。
//
//  ⚠ 时钟必须与设计一致：本文件写死 49999（对应 50 MHz）。
//     如果板上实际是 27 MHz，就必须改成 26999，否则读数会偏大 1.85 倍。
//==========================================================================

module counter(
    input  logic         clk,              // 计时基准时钟
    input  logic         rst,              // 复位（清零全部）

    input  logic [31:0]  perip_wdata,      // 来自 CPU 的写数据（魔数）
    input  logic         cnt_wen,          // 本模块被写中时的写使能
    output logic [31:0]  perip_rdata,      // 读回值（= 毫秒数）
    output logic [31:0]  ms_value,         // 毫秒数（送给 LED / 串口的副本）
    output logic         ms_running        // 1 = 正在计时
);

    logic [15:0] cnt_1ms;    // 1 毫秒内的时钟计数（0..49999）
    logic [31:0] cnt_ms;     // 毫秒计数（这就是最终要报的数）
    logic        start;      // 运行标志

    //------------------------------------------------------------------
    // 启动 / 停表 控制
    //   只有 CPU 写进来特定的两个魔数才动作，其它写值一律忽略
    //   停表时**不清零** cnt_ms —— 要的就是"定格"住最后的数字
    //------------------------------------------------------------------
    always_ff @(posedge clk) begin
        if (rst) begin
            start <= 0;                                   // 复位后不跑
        end else if (cnt_wen & perip_wdata == 32'h8000_0000) begin
            start <= 1;                                   // 魔数 1：启动
        end else if (cnt_wen & perip_wdata == 32'hFFFF_FFFF) begin
            start <= 0;                                   // 魔数 2：停表
        end
    end

    //------------------------------------------------------------------
    // 1 毫秒分频
    //   数到 49999 就回 0（50000 个周期正好 1 ms @50MHz）
    //   不跑的时候强制清零，保证每次启动都从"完整的一毫秒"开始
    //------------------------------------------------------------------
    always_ff @(posedge clk) begin
        if (rst) begin
            cnt_1ms <= 0;
        end else if (start) begin
            if (cnt_1ms == 49999) begin   // 50000 拍 = 1 ms（50 MHz）
                cnt_1ms <= 0;
            end else begin
                cnt_1ms <= cnt_1ms + 1;
            end
        end else begin
            cnt_1ms <= 0;                 // 停表时清零，下次启动对齐
        end
    end

    //------------------------------------------------------------------
    // 毫秒累加
    //   只有在"正在跑"且"刚好数满 1 ms"的那一拍才 +1
    //   停表后这个值就定住了 → 读出来就是定格成绩
    //------------------------------------------------------------------
    always_ff @(posedge clk) begin
        if (rst) begin
            cnt_ms <= 0;
        end else if (start && cnt_1ms == 49999) begin
            cnt_ms <= cnt_ms + 1;
        end
    end

    // 读口：CPU load 0x8020_0050 时拿到当前毫秒数（组合输出，同拍有效）
    assign perip_rdata = cnt_ms;
    // 给板级用：LED 和串口都拿这份值
    assign ms_value    = cnt_ms;
    assign ms_running  = start;

endmodule
