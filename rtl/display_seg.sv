`timescale 1ns/1ps

//==========================================================================
//  display_seg.sv — 8 位数码管动态扫描（时分复用）
//--------------------------------------------------------------------------
//  板上的 8 位数码管并不是 8×7=56 根线独立驱动，而是：
//      · 8 个"位选"（哪一位亮）—— 由 ans[7:0] 控制
//      · 7 个"段选"（这一位显示什么）—— seg1~seg4 中的哪一组
//  所以必须"快速轮流点亮每一位"，靠人眼视觉暂留看起来像同时亮。
//
//  本模块的做法：
//      count 自由计数，用 count[4] 做 16 分频（50 MHz / 16 ≈ 3.1 MHz 翻转）
//      为了让每一组都有更长的点亮时间，实际上只分了两大组：
//        count[4]=0 : 点亮奇数位（ans=10101010），显示 s 的高半字节
//        count[4]=1 : 点亮偶数位（ans=01010101），显示 s 的低半字节
//      这样每一位的刷新率 ≈ 50MHz / 32 ≈ 1.56 MHz，远高于人眼闪烁阈值。
//
//  输入 s 是 32 位，被拆成 8 个十六进制数字（每位 4 bit）：
//      s[31:28] s[27:24] s[23:20] s[19:16] s[15:12] s[11:8] s[7:4] s[3:0]
//==========================================================================
module display_seg (
    input  logic          clk,      // 50 MHz
    input  logic          rst,      // 高有效复位
    input  logic [31:0]   s,        // 要显示的 32 位数据（8 个十六进制数字）
    output logic [6:0]    seg1,     // 四组段选（分别送 4 个数码管）
    output logic [6:0]    seg2,
    output logic [6:0]    seg3,
    output logic [6:0]    seg4,
    output logic [7:0]    ans       // 位选（1 = 该位点亮）
);
    logic  [4:0]   count;                          // 扫描计数器
    logic  [3:0]   digit1, digit2, digit3, digit4; // 当前这一组要显示的 4 个数字

    //----------------------------------------------------------------------
    // 扫描计数器：每个时钟 +1，count[4] 每 16 个时钟翻转一次
    //----------------------------------------------------------------------
    always@(posedge clk or posedge rst) begin
        if(rst)
            count <= 0;
        else
            count <= count + 1;
    end

    //----------------------------------------------------------------------
    // 位选 + 取数（组合）
    //   第一大组：点亮 ans 的奇数位，显示 s 的 4 个高半字节
    //   第二大组：点亮 ans 的偶数位，显示 s 的 4 个低半字节
    //----------------------------------------------------------------------
    always @(*)
    case(count[4])
        0: begin
            ans    = 8'b10101010;                  // 奇数位亮
            digit1 = s[7:4];                       // 注意：从 [7:4] 开始，不是 [7:0]
            digit2 = s[15:12];
            digit3 = s[23:20];
            digit4 = s[31:28];
        end

        1: begin
            ans    = 8'b01010101;                  // 偶数位亮
            digit1 = s[3:0];
            digit2 = s[11:8];
            digit3 = s[19:16];
            digit4 = s[27:24];
        end

    endcase

    //----------------------------------------------------------------------
    // 4 个译码器（每个负责一位）
    //----------------------------------------------------------------------
    seg7 SEG1(.din(digit1),.dout(seg1));
    seg7 SEG2(.din(digit2),.dout(seg2));
    seg7 SEG3(.din(digit3),.dout(seg3));
    seg7 SEG4(.din(digit4),.dout(seg4));
endmodule
