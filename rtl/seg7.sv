`timescale 1ns/1ps

//==========================================================================
//  seg7.sv — 七段数码管译码器（1 个十六进制数字 → 7 根段线）
//--------------------------------------------------------------------------
//  这是整个工程里最简单、也最应该先写对的模块：纯组合查表。
//
//  段线顺序（本项目约定，共阴极数码管，1 = 点亮）：
//        dout[6] = g
//        dout[5] = f
//        dout[4] = e
//        dout[3] = d
//        dout[2] = c
//        dout[1] = b
//        dout[0] = a
//
//        --a--
//       |     |
//       f     b
//       |     |
//        --g--
//       |     |
//       e     c
//       |     |
//        --d--
//
//  例：数字 0 需要 a,b,c,d,e,f 亮、g 灭
//      → {g,f,e,d,c,b,a} = {0,1,1,1,1,1,1} = 7'b011_1111 ✔
//  例：数字 1 只有 b,c 亮
//      → {0,0,0,0,1,1,0} = 7'b000_0110 ✔
//==========================================================================
module seg7(
    input  logic [3:0]  din,        // 4 位二进制数字（0~15）
    output logic [6:0]  dout        // 7 根段线（高有效）
);

    //----------------------------------------------------------------------
    // 查表：16 个字符的段码
    //   0~9 是数字，a~f 是十六进制字母
    //   default 给 0（全灭），防止 X 传播
    //----------------------------------------------------------------------
    always_comb begin
        case(din)
            4'h0: dout = 7'b011_1111;   // 0 : a b c d e f
            4'h1: dout = 7'b000_0110;   // 1 : b c
            4'h2: dout = 7'b101_1011;   // 2 : a b d e g
            4'h3: dout = 7'h4f;         // 3 : a b c d g
            4'h4: dout = 7'h66;         // 4 : b c f g
            4'h5: dout = 7'h6d;         // 5 : a c d f g
            4'h6: dout = 7'h7d;         // 6 : a c d e f g
            4'h7: dout = 7'h07;         // 7 : a b c
            4'h8: dout = 7'h7f;         // 8 : 全亮
            4'h9: dout = 7'h6f;         // 9 : a b c d f g
            4'ha: dout = 7'h77;         // A
            4'hb: dout = 7'h7c;         // b
            4'hc: dout = 7'h39;         // C
            4'hd: dout = 7'h5e;         // d
            4'he: dout = 7'h79;         // E
            4'hf: dout = 7'h71;         // F
            default: dout = 7'h00;      // 非法输入 → 全灭
        endcase
    end

endmodule
